// The Go standard library has no text rasterizer, so image mode renders text
// with a small embedded bitmap font. This is the well-known public-domain
// "font5x7" table (Adafruit font5x7.h / glcdfont.c, "Standard ASCII 5x7
// font").
//
// Each glyph is 5 bytes, one byte per COLUMN from left to right; bit row 0 is
// the top row, bit row 7 the bottom. Rows 0..6 carry the body of the letter,
// row 7 is the descender row (g, j, p, q, y and punctuation sit on it), so
// the baseline runs between rows 6 and 7.
//
// Scaling: glyphs are 5x8 pixels at 12 pt (fontBase); every other size is
// rendered by nearest-neighbour scaling of the pixel grid, scale = size/12.
// There is no anti-aliasing: edges are hard. Bold text is faked by drawing
// each glyph twice with a 1 px (at 12 pt) horizontal offset.
const (
	glyphCols    = 5    // columns per glyph
	glyphRows    = 8    // rows per glyph (7 body + 1 descender)
	glyphAdvance = 6    // columns of advance per glyph at scale 1 (5 + 1 space)
	fontBase     = 12.0 // size in pt at which glyphs are 5x8 px
)

