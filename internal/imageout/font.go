// glyphAt returns the 5 column bytes for ASCII r (32..126).
func glyphAt(r rune) []byte {
	if r < 32 || r > 126 {
		return nil
	}
	off := int(r-32) * glyphCols
	return fontData[off : off+glyphCols]
}

// measureString returns the rasterized width of s in output pixels at the
// given size: one fixed-width cell of glyphAdvance pixels per rune at 12 pt,
// scaled linearly. Non-ASCII runes (e.g. bullets) count as one cell.
func measureString(s string, size float64) float64 {
	gs := size / fontBase
	return float64(len([]rune(s))) * glyphAdvance * gs
}

// drawString paints s into img with the bitmap font. (x, y) is the baseline
// in canvas pixels (the y layout op coordinate, scaled to pixels). size is
// the font size in points; scale = size/12 maps each font pixel to a
// block of pixels (nearest neighbour). bold fakes weight by drawing each
// glyph twice with a 1 px offset. The bullet rune is drawn as a small solid
// block, since the font table only covers ASCII.
func drawString(img *image.NRGBA, x, y int, s string, size float64, bold bool, c color.NRGBA) {
	gs := size / fontBase
	boldOff := 1
	if gs > 1 {
		boldOff = int(math.Round(gs))
	}
	fx := float64(x)
	baseY := float64(y)
	for _, r := range s {
		switch {
		case r == '\u2022':
			// bullet: solid block centred on the glyph cell
			blx := int(math.Round(fx + gs))
			bly := int(math.Round(baseY - 5*gs))
			fillBlock(img, blx, bly, 3*gs, c)
		case r >= 32 && r <= 126:
			cols := glyphAt(r)
			for col := 0; col < glyphCols; col++ {
				if cols[col] == 0 {
					continue
				}
				px := int(math.Floor(fx + float64(col)*gs))
				for row := 0; row < glyphRows; row++ {
					if cols[col]&(1<<row) == 0 {
						continue
					}
					// rows 0..6 sit above the baseline, row 7 below it
					py := int(math.Floor(baseY - float64(glyphRows-1)*gs + float64(row)*gs))
					fillBlock(img, px, py, gs, c)
					if bold {
						fillBlock(img, px+boldOff, py, gs, c)
					}
				}
			}
		}
		fx += glyphAdvance * gs
	}
}

// fillBlock paints a gs x gs block of c at (x, y), clipped to the canvas.
func fillBlock(img *image.NRGBA, x, y int, gs float64, c color.NRGBA) {
	w := int(math.Ceil(gs))
	if w < 1 {
		w = 1
	}
	b := img.Bounds()
	for dy := 0; dy < w; dy++ {
		for dx := 0; dx < w; dx++ {
			px, py := x+dx, y+dy
			if px < b.Min.X || px >= b.Max.X || py < b.Min.Y || py >= b.Max.Y {
				continue
			}
			img.SetNRGBA(px, py, c)
		}
	}
}
